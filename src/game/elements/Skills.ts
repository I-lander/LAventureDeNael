export function getSkillDef(kind: SkillKind): SkillDef {
  const skillDef = SKILLS.find((entry) => entry.kind === kind);
  if (!skillDef) {
    throw new Error(`Unknown skill kind ${kind}`);
  }
  return skillDef;
}

